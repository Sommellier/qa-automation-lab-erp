import { UserRole } from '@prisma/client';
import { Router } from 'express';
import { ProductController } from '../controllers/product.controller.js';
import { StockController } from '../controllers/stock.controller.js';
import { authenticate } from '../middlewares/authenticate.middleware.js';
import { authorizeRoles } from '../middlewares/authorize.middleware.js';
import { validateBody } from '../middlewares/validate.middleware.js';
import { PrismaProductRepository } from '../repositories/product.repository.js';
import { PrismaCategoryRepository } from '../repositories/category.repository.js';
import { PrismaStockRepository } from '../repositories/stock.repository.js';
import { createProductSchema, updateProductSchema, updateProductStatusSchema } from '../schemas/product.schema.js';
import { ProductService } from '../services/product.service.js';
import { StockService } from '../services/stock.service.js';
import { auditLogger } from '../services/audit.service.js';
import { adjustStockSchema, manualStockSchema } from '../schemas/stock.schema.js';

const stockService = new StockService(new PrismaStockRepository(), auditLogger);
const controller = new ProductController(new ProductService(new PrismaProductRepository(), auditLogger, stockService, new PrismaCategoryRepository()));
const stockController = new StockController(stockService);
export const productRouter = Router();
productRouter.use(authenticate);
productRouter.get('/', authorizeRoles(UserRole.ADMIN, UserRole.ANALISTA, UserRole.VISUALIZADOR), controller.list);
productRouter.get('/:id/stock/movements', authorizeRoles(UserRole.ADMIN, UserRole.ANALISTA, UserRole.VISUALIZADOR), stockController.list);
productRouter.post('/:id/stock/entry', authorizeRoles(UserRole.ADMIN), validateBody(manualStockSchema), stockController.entry);
productRouter.post('/:id/stock/exit', authorizeRoles(UserRole.ADMIN), validateBody(manualStockSchema), stockController.exit);
productRouter.post('/:id/stock/adjust', authorizeRoles(UserRole.ADMIN), validateBody(adjustStockSchema), stockController.adjust);
productRouter.get('/:id', authorizeRoles(UserRole.ADMIN, UserRole.ANALISTA, UserRole.VISUALIZADOR), controller.getById);
productRouter.post('/', authorizeRoles(UserRole.ADMIN, UserRole.ANALISTA), validateBody(createProductSchema), controller.create);
productRouter.patch('/:id', authorizeRoles(UserRole.ADMIN, UserRole.ANALISTA), validateBody(updateProductSchema), controller.update);
productRouter.patch('/:id/status', authorizeRoles(UserRole.ADMIN), validateBody(updateProductStatusSchema), controller.updateStatus);
